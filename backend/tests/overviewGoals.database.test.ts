import test from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import jwt from 'jsonwebtoken';
import { prisma } from '../src/lib/prisma';
import { app } from '../src/index';
import { bangkokToday } from '../src/lib/goalCalculations';
import { lastCompletedMonth, goalCashFlow } from '../src/lib/goalFeasibility';
import { loadCycleContext } from '../src/lib/cycle';
const db=new URL(process.env.DATABASE_URL!).pathname.slice(1);
if(!db.startsWith('spendsense_goals_test_overview_')||process.env.GOALS_TEST_DATABASE!==db)throw Error('Explicit isolated test DB required');
test('real HTTP/PostgreSQL overview and feasibility ownership and read-only behavior',async t=>{
 process.env.JWT_SECRET=randomUUID();
 const server=app.listen(0,'127.0.0.1');await new Promise<void>(r=>server.once('listening',r));
 const address=server.address();assert.ok(address&&typeof address!=='string');
 t.after(async()=>{await new Promise<void>(r=>server.close(()=>r()));await prisma.$disconnect();});
 const account=async()=>{const u=await prisma.user.create({data:{email:randomUUID()+'@example.invalid',passwordHash:'synthetic-no-login'}});return {...u,token:jwt.sign({userId:u.id,email:u.email},process.env.JWT_SECRET!)};};
 const a=await account(),b=await account(),today=bangkokToday(),period=lastCompletedMonth(await loadCycleContext(prisma,a.id),today);
 const inc=await prisma.category.create({data:{name:randomUUID(),type:'income'}}),exp=await prisma.category.create({data:{name:randomUUID(),type:'expense'}});
 const add=(owner:string,type:'income'|'expense',amount:string,date:string)=>prisma.transaction.create({data:{userId:owner,type,amount,categoryId:type==='income'?inc.id:exp.id,transactionDate:new Date(date+'T00:00:00Z')}});
 async function get(path:string,who=a,status=200){const r=await fetch('http://127.0.0.1:'+address.port+path,{headers:{Authorization:'Bearer '+who.token}});assert.equal(r.status,status,path);if(status===200)assert.match(r.headers.get('cache-control')??'',/private, no-store/);return r.json() as Promise<any>;}
 assert.equal((await fetch('http://127.0.0.1:'+address.port+'/goals')).status,401);
 const g=await prisma.goal.create({data:{userId:a.id,name:'synthetic',targetAmount:'100',targetDate:new Date('2099-12-28') /* fixed far deadline: never overdue, independent of wall clock */,categoryKey:'other'}});
 const empty=await get('/dashboard?month='+period.month);assert.equal(empty.summary.savingRate.percent,null);
 assert.equal((await get('/goals')).data[0].feasibility.status,'no_transactions');
 await add(a.id,'income','100.00',period.startDate);await add(a.id,'expense','20.01',period.endDate);
 await add(a.id,'income','9999',today);await add(b.id,'income','888888',period.startDate);
 const before=JSON.stringify({tx:await prisma.transaction.findMany({where:{userId:a.id},orderBy:{id:'asc'}}),goals:await prisma.goal.findMany({where:{userId:a.id}}),ledger:await prisma.goalLedgerEntry.findMany({where:{userId:a.id}})});
 const dashboard=await get('/dashboard?month='+period.month);assert.equal(dashboard.summary.savingRate.percent,'79.99');
 const list=await get('/goals'),detail=await get('/goals/'+g.id);
 assert.deepEqual(list.data[0].feasibility,detail.feasibility);
 assert.equal(detail.feasibility.cashFlow.netCashFlow,'79.99');assert.equal(detail.feasibility.cashFlow.transactionCount,2);
 assert.equal((await get('/goals',b)).data.length,0);await get('/goals/'+g.id,b,404);
 await get('/goals?userId='+b.id,a,400);
 const behavior=await get('/behavior');assert.equal(behavior.readiness.current.ready,false);assert.equal(behavior.findings.length,0);
 const queue=await get('/anomaly/queue?filter=waiting&limit=1');assert.equal(queue.total,0);
 const after=JSON.stringify({tx:await prisma.transaction.findMany({where:{userId:a.id},orderBy:{id:'asc'}}),goals:await prisma.goal.findMany({where:{userId:a.id}}),ledger:await prisma.goalLedgerEntry.findMany({where:{userId:a.id}})});
 assert.equal(after,before);
 // Explicit date injection verifies reference boundary independently of wall clock.
 await add(b.id,'income','50','2024-02-29');await add(b.id,'expense','0.07','2024-02-01');await add(b.id,'expense','0.01','2024-02-01');await add(b.id,'income','777','2024-03-01');
 const leap=await prisma.$transaction(tx=>goalCashFlow(tx,b.id,'2024-03-01'));
 assert.equal(leap.netCashFlow,'49.92');assert.equal(leap.period.endDate,'2024-02-29');
 const c=await account();
 const rows=Array.from({length:60},(_,i)=>{const date=new Date(today+'T00:00:00Z');date.setUTCDate(date.getUTCDate()-i-1);return {userId:c.id,type:'expense' as const,amount:i<30?'20.00':'10.00',categoryId:exp.id,transactionDate:date};});
 await prisma.transaction.createMany({data:rows});
 const ready=await get('/behavior',c);
 assert.equal(ready.readiness.current.ready,true);
 assert.equal(ready.readiness.comparisonReady,true);
 assert.ok(ready.findings.length>0);
 assert.equal(ready.facts.summary.current.amount,'600.00');
 assert.equal(ready.facts.summary.previous.amount,'300.00');
 assert.equal((await get('/dashboard?month='+period.month,c)).summary.savingRate.reason,'no_income');
 console.log('PASS isolated PostgreSQL auth, ownership, month cutoff, Decimal, null rate, readiness and unchanged Transaction/Goal/ledger');
});
